// dreamer-task-run-def.test.ts — пин методички инцидент-разбора: шаг 8 дефа
// dreamer несёт контракты, на которых стоит задачный прогон.
import { existsSync, readFileSync } from "node:fs"
import { join } from "node:path"
import { describe, expect, test } from "bun:test"

/** Шаг 8 «Инцидент-разбор (режим «задача»)» (задача 20261111190300-sflkkqh)
 *  — текстовая методичка, применяемая LLM на спавне задачного прогона.
 *  Регрессия здесь тихая: секцию легко снести очередной правкой дефа, демона
 *  это не сломает (код не читает шаг 8), и живой прогон молча потеряет цикл
 *  «сигнал → разбор → реестр → задача». Пин — по исходнику (CI-safe, как
 *  пины в cron-lib.test.ts / dreamer-model.test.ts): слом любого контракта
 *  ниже двигает сигнал на CI. */
const defPath = join(import.meta.dir, "..", "agents", "dreamer.md")

function def(): string {
  expect(existsSync(defPath)).toBe(true)
  return readFileSync(defPath, "utf-8")
}

describe("пин дефа dreamer — методичка инцидент-разбора (шаг 8)", () => {
  test("секция шага 8 существует с каноничным заголовком", () => {
    expect(def()).toContain('### 8. Инцидент-разбор (режим «задача»)')
  })

  test("слаг реестра — каноничный (дример ищет док по нему)", () => {
    expect(def()).toContain("platform/Инцидент-реестр конвейера")
  })

  test("граница применимости: перечисление шага 3 и клоза шага 8 согласованы", () => {
    // Оба места правки одного смысла (дельта-раунд 2, Low-1): несматченный
    // проект не должен читать шаг 8 как «всегда», посессионный — как «мне тоже».
    expect(def()).toContain("инцидент-разбор (шаг 8) — только задачный прогон")
    expect(def()).toContain("Посессионный прогон этот шаг не делает")
  })

  test("деградация покрывает шаг 8 («шаги 4-8», не старое «4-6»)", () => {
    // Недоступная вика = нет ни search по реестру, ни append: без клозы
    // автономный flash-дример поведёт себя непредсказуемо (ревью плана, Common).
    expect(def()).toContain("шаги 4-8 пропусти")
  })

  test("приоритет над шагом 5 заявлен (тихая деградация «всё разовое»)", () => {
    // Дельта-раунд 2, Low-2: без оговорки часть прогонов может пропустить
    // запись реестра, мотивируя шагом 5 («вердикты не тащи в вики»).
    expect(def()).toContain("Приоритетен и над шагом 5")
  })

  test("ADR-сверка перед заводом паттерн-задачи (гашёное решение — не заводим)", () => {
    // Дельта-раунд 2, Low-3: смоук завёл кандидата против ADR-088 —
    // без сверки механика систематически генерирует задачи против отказов.
    expect(def()).toContain("Superseded")
    expect(def()).toContain("ADR-папкой проекта боли")
  })

  test("формат записи реестра несёт метку и исход (поиск повторов матчит по метке)", () => {
    expect(def()).toContain("исход: разовый | повтор задачи")
    expect(def()).toContain("Метки:")
  })

  test("конвейерные маркеры закреплены (шторм 20261112074307-zq2iv3o)", () => {
    // Блок «Конвейерные маркеры»: димер обязан видеть рестарты serve,
    // убитые ходы и аутеджи в дампах — без пина блок сносится правкой дефа
    // тихо (демон не читает шаг 8), и молчание дримеров возвращается.
    expect(def()).toContain("Конвейерные маркеры (таймауты/прерывания ходов)")
    expect(def()).toContain("The server restarted while you were working")
    expect(def()).toContain("The previous response was interrupted")
    expect(def()).toContain("[sticky-retry] provider outage")
  })

  test("SQL-проба конвейерных маркеров: рестарты + idle_outcome по пакету сессий", () => {
    // Полный подсчёт мимо лимита timeline дампа; исход сессии — носитель
    // «тихой смерти» (failed/interrupted/succeeded-без-финала).
    expect(def()).toContain("like '%server restarted%'")
    expect(def()).toContain("idle_outcome")
  })

  test("шторм = задача на паттерн даже при успешном Done (таймауты не блокируют закрытие)", () => {
    // Ключевое правило разрыва наблюдаемости: без него шторма тонут
    // в успешно закрытых задачах — исход смоука 20261112074307-zq2iv3o.
    expect(def()).toContain("задача на паттерн даже если задача формально закрылась")
    expect(def()).toContain("таймауты не блокируют Done")
  })
})
