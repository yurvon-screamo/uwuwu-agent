// triage-zoomout-flags.test.ts — пин-тест zoom-out флагов валидации черновиков
// (задача 20261109231808-gigkqxr): три дешёвые проверки (реюз по PR-ленте,
// Non-goals README, «правило вместо задачи») живут в методичке triage/agent.md —
// пассивные флаги-строки в теле, не вердикты (анти-стоп-кран, ADR-074).
// Контент-пин: частичный конфликт мержа → тест падает и напоминает, что правка
// методички — осознанное решение. Поведенческая половина (флаг появляется в
// теле черновика при пересекающемся PR) — LLM-поведение: живой позитивный
// контроль синтетическими черновиками после мерджа, не автотест.
// Интеграционный слой материализации дефа (демон доносит промпт из репо) —
// tests/triage-gates-reverted.test.ts, здесь не дублируется; исторические
// гейт-сигнатуры тоже — за ними уже следит тот файл.
import { describe, test, expect } from "bun:test"
import { readFileSync } from "node:fs"
import { join } from "node:path"

const REPO = join(import.meta.dir, "..")
const AGENT_MD = join(REPO, "triage", "agent.md")

/** Сигнатуры флагового шага методички: заголовок шага, три проверки, контракт
 *  записи (формат строки), семантика отказа gh, порог честности. */
const FLAG_SIGNATURES = [
  "Zoom-out флаги", // шаг 3: заголовок
  "не вердикт", // флаг не меняет статусы/вердикты
  "Реюз", // проверка 1
  "gh pr list --state all --limit 50", // проверка 1: лимит+окно
  "пропускается тихо", // проверка 1: отказ инструмента — без эскалации
  "Non-goals проекта", // проверка 2
  "Правило вместо задачи", // проверка 3
  "механизм ради механизма", // маркер проверки 3
  "🚩 Триаж:", // формат флаг-строки в теле
]

/** Канон draft-ack вердиктов (hub.ts DraftVerdict): дословно, без новых —
 *  флаги не заводят пятый+ вердикт. */
const VERDICTS_BLOCK =
  "Вердикты канонические, ровно эти: `todo` · `merge` · `rm` · `пишется` · `обсуждение`."

describe("zoom-out флаги триажа: контракт методички", () => {
  const md = readFileSync(AGENT_MD, "utf-8")

  test("triage/agent.md — флаговые сигнатуры на месте", () => {
    for (const s of FLAG_SIGNATURES) {
      expect(md).toContain(s)
    }
  })

  test("triage/agent.md — канон draft-ack вердиктов не расширился", () => {
    expect(md).toContain(VERDICTS_BLOCK)
  })
})
