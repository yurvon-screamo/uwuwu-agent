// e2e-tag.ts — конвенция маркера синтетических сессий (кросс-демонный контракт).
//
// Демон триажа в e2e-режиме (UWUWU_TRIAGE_E2E=1) помечает сессию диалога
// префиксом при создании; дример фильтрует помеченные сессии из
// пост-обработки. Без маркера одноразовый e2e-риг 04.11 породил 30
// дример-прогонов на 31 smoke-сессии (≈1.14M входных токенов пустой
// пост-обработки).
export const E2E_SESSION_PREFIX = "[e2e] "

export const withE2ETag = (title: string): string => `${E2E_SESSION_PREFIX}${title}`
